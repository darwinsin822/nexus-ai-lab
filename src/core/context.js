import fs from 'node:fs';
import path from 'node:path';
import { findNexusRoot } from './config.js';

/**
 * Compresses and packages relevant context for a specific task
 */
export function buildContextPack(task, options = {}) {
  const root = options.root || findNexusRoot();
  const contextDir = path.join(root, '.nexus', 'context');
  if (!fs.existsSync(contextDir)) {
    fs.mkdirSync(contextDir, { recursive: true });
  }

  const memoryDir = path.join(root, '.nexus', 'memory');
  let architectureSummary = '';
  let decisionsSummary = '';
  let conventionsSummary = '';

  const readIfExist = (file) => {
    const full = path.join(memoryDir, file);
    if (fs.existsSync(full)) {
      return fs.readFileSync(full, 'utf8').trim();
    }
    return '';
  };

  architectureSummary = readIfExist('architecture.md');
  decisionsSummary = readIfExist('decisions.md');
  conventionsSummary = readIfExist('conventions.md');

  // File snippet inspection
  let fileSnippets = '';
  if (Array.isArray(task.files) && task.files.length > 0) {
    fileSnippets = '### Target Files\n';
    for (const relFile of task.files.slice(0, 5)) {
      const full = path.join(root, relFile);
      if (fs.existsSync(full) && fs.statSync(full).isFile()) {
        const content = fs.readFileSync(full, 'utf8');
        // Compress: Take first 80 lines if large
        const lines = content.split('\n');
        const preview = lines.slice(0, 80).join('\n');
        fileSnippets += `\n#### \`${relFile}\` (${lines.length} lines)\n\`\`\`\n${preview}\n${lines.length > 80 ? '... [truncated for context efficiency]' : ''}\n\`\`\`\n`;
      }
    }
  }

  const packContent = `# TASK CONTEXT PACK: ${task.id}
**Title:** ${task.title || 'Untitled Task'}  
**Category:** ${task.category || 'GENERAL'}  
**Mode:** ${task.mode || 'ECONOMY'}  
**Target Engine:** ${task.engine || 'opencode'}  
**Timestamp:** ${new Date().toISOString()}  

---

## 1. Task Objective
${task.description || task.title}

${conventionsSummary ? `## 2. Project Conventions\n${conventionsSummary}\n` : ''}
${decisionsSummary ? `## 3. Important Historical Decisions\n${decisionsSummary}\n` : ''}
${architectureSummary ? `## 4. Architecture Overview\n${architectureSummary}\n` : ''}
${fileSnippets ? `## 5. File References\n${fileSnippets}` : ''}

---
*Generated by Nexus Context Manager (Compressed to minimize token usage).*
`;

  const packPath = path.join(contextDir, `${task.id}.md`);
  fs.writeFileSync(packPath, packContent, 'utf8');

  return {
    path: packPath,
    content: packContent
  };
}

export function saveChangeSummary(taskId, summary, options = {}) {
  const root = options.root || findNexusRoot();
  const changesDir = path.join(root, '.nexus', 'changes');
  if (!fs.existsSync(changesDir)) {
    fs.mkdirSync(changesDir, { recursive: true });
  }

  const changeContent = `# TASK CHANGE SUMMARY: ${taskId}
**Date:** ${new Date().toISOString()}  
**Status:** ${summary.status || 'COMPLETED'}  
**Engine:** ${summary.engine || 'unknown'}  
**Agent:** ${summary.agent || 'unknown'}  

## 1. What Changed
${summary.whatChanged || 'No description provided.'}

## 2. Why
${summary.why || 'Fulfill task requirements.'}

## 3. Files Modified
${(summary.files || []).map(f => `- \`${f}\``).join('\n') || '- None recorded'}

## 4. Tests & Verification
${summary.tests || 'Verification executed via Quality Gate.'}

## 5. Risks & Pending Items
${summary.risks || 'No pending risks identified.'}
`;

  const changePath = path.join(changesDir, `${taskId}.md`);
  fs.writeFileSync(changePath, changeContent, 'utf8');
  return changePath;
}
