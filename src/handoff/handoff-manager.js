import fs from 'node:fs';
import path from 'node:path';
import { findNexusRoot } from '../core/config.js';

export class HandoffManager {
  constructor(options = {}) {
    this.root = options.root || findNexusRoot();
    this.nexusDir = path.join(this.root, '.nexus');
    this.ensureDir();
  }

  ensureDir() {
    if (!fs.existsSync(this.nexusDir)) {
      try {
        fs.mkdirSync(this.nexusDir, { recursive: true });
      } catch (e) {}
    }
  }

  writeArtifact(filename, content) {
    this.ensureDir();
    const filePath = path.join(this.nexusDir, filename);
    fs.writeFileSync(filePath, content, 'utf8');
    return filePath;
  }

  readArtifact(filename) {
    const filePath = path.join(this.nexusDir, filename);
    if (fs.existsSync(filePath)) {
      return fs.readFileSync(filePath, 'utf8');
    }
    return null;
  }

  /**
   * Creates a formal handoff transfer document between two agents or engines
   */
  createHandoff(fromAgent, toAgent, payload = {}) {
    const timestamp = new Date().toISOString();
    const handoffDoc = `# NEXUS AGENT HANDOFF RECORD
**Timestamp:** ${timestamp}  
**From:** ${fromAgent.engine} / ${fromAgent.agent}  
**To:** ${toAgent.engine} / ${toAgent.agent}  
**Stage:** ${payload.stage || 'PROGRESSION'}  

---

## 1. Objective
${payload.objective || 'Complete assigned task progression'}

## 2. Context & Decisions Taken
${payload.decisions || 'Standard modular implementation following project conventions.'}

## 3. Files Modified
${(payload.filesModified || []).map(f => `- \`${f}\``).join('\n') || '- None recorded'}

## 4. Test Results & Quality Evidence
${payload.testResults || 'Pending automated test validation.'}

## 5. Next Steps for Receiving Agent
${payload.nextSteps || 'Execute assigned phase and report back to Nexus Orchestrator.'}

---
*Generated by Nexus Handoff Subsystem.*
`;

    this.writeArtifact('handoff.md', handoffDoc);
    if (payload.plan) this.writeArtifact('plan.md', payload.plan);
    if (payload.execution) this.writeArtifact('execution.md', payload.execution);
    if (payload.testReport) this.writeArtifact('test-report.md', payload.testReport);
    if (payload.review) this.writeArtifact('review.md', payload.review);
    if (payload.task) this.writeArtifact('task.json', JSON.stringify(payload.task, null, 2));

    return handoffDoc;
  }
}

export const handoffManager = new HandoffManager();
